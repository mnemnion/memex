test "fixture rust set bytes verify and contain exact keys" {
    const set = fst.Fst(void).init(rust_set_fixture);
    try set.verify();
    try expectEqual(@as(u64, 3), set.len);
    try expect(set.contains("a"));
    try expect(set.contains("ab"));
    try expect(set.contains("b"));
    try expect(!set.contains(""));
    try expect(!set.contains("c"));
}

test "fixture rust map bytes verify and return exact values" {
    const map = fst.Fst(u64).init(rust_map_fixture);
    try map.verify();
    try expectEqual(@as(u64, 3), map.len);
    try expectEqual(@as(?u64, 1), map.get("a"));
    try expectEqual(@as(?u64, 3), map.get("ab"));
    try expectEqual(@as(?u64, 10), map.get("b"));
    try expectEqual(@as(?u64, null), map.get("c"));
}

test "fixture rust prefix map keeps terminal final output readable" {
    const map = fst.Fst(u64).init(rust_prefix_final_map_fixture);
    try map.verify();
    try expectEqual(@as(u64, 3), map.len);
    try expectEqual(@as(?u64, 10), map.get("a"));
    try expectEqual(@as(?u64, 3), map.get("ab"));
    try expectEqual(@as(?u64, 20), map.get("b"));
}

test "fixture rust direct index set bytes use byte-to-index lookup" {
    const set = fst.Fst(void).init(rust_direct_index_set_fixture);
    try set.verify();
    try expectEqual(@as(u64, 33), set.len);
    try expect(set.contains(&.{0x21}));
    try expect(set.contains(&.{0x31}));
    try expect(set.contains(&.{0x41}));
    try expect(!set.contains(&.{0x20}));
    try expect(!set.contains(&.{0x42}));
}

